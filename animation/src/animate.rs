use bevy::{
    animation::{
        AnimationClip, AnimationTargetId, animated_field,
        animation_curves::{AnimatableCurve, AnimatableKeyframeCurve, AnimatableProperty},
    },
    asset::uuid::Uuid,
    curve::{Curve, CurveExt, EaseFunction, EasingCurve, interval},
    ecs::{component::Component, reflect::ReflectComponent},
    math::{Quat, Rot2, Vec2, Vec3},
    reflect::{FromReflect, GetTypeRegistration, Reflect, Typed, std_traits::ReflectDefault},
    transform::components::Transform,
    ui::UiTransform,
    utils::default,
};

/// Initial component value to set before the animation starts.
/// This should usually be ignored when working with custom animations.
#[derive(Clone, Debug, PartialEq, Reflect)]
#[reflect(Clone, PartialEq, Debug)]
pub enum InitialAnimateValue {
    /// Initial value for [Transform::translation]
    Translate(Vec3),
    /// Initial value for [UiTransform::translation]
    UiTranslate(Vec2),
    /// Initial value for [Transform::rotation]
    Rotate(Quat),
    /// Initial value for [UiTransform::rotation]
    UiRotate(Rot2),
    /// Initial value for [Transform::scale]
    Scale(Vec3),
    /// Initial value for [UiTransform::scale]
    UiScale(Vec2),
}

/// Component to animate other Components. Use one of the various helper functions, i.e. [Animate::translate]
#[derive(Clone, Component, Debug, Reflect)]
#[reflect(Clone, Component, Debug, Default)]
pub struct Animate {
    /// The animation clip for the animation. Typically generated by using one of the helper functions
    pub animation: AnimationClip,
    /// The animation target id for the animation. Typically generated by using one of the helper functions
    ///
    /// **Do not change this after using a helper function or things will break**
    pub target_id: AnimationTargetId,
    /// The delay of the animation
    pub delay: f32,
    /// Set an initial value for the component to animate to prevent a jump when the animation starts.
    /// You can probably ignore this if you are making a custom animation.
    pub init: Option<InitialAnimateValue>,
}

impl Default for Animate {
    fn default() -> Self {
        Self {
            target_id: AnimationTargetId(Uuid::default()),
            ..default()
        }
    }
}

impl Animate {
    /// Build an animation, animating a custom property `P`
    pub fn build<P>(
        init: impl Into<Option<InitialAnimateValue>>,
        property: P,
        start: P::Property,
        end: P::Property,
        time: f32,
        ease_function: EaseFunction,
    ) -> Self
    where
        P: AnimatableProperty + Clone,
        P::Property: Clone + std::fmt::Debug + FromReflect + GetTypeRegistration + Typed,
        AnimatableKeyframeCurve<P::Property>: Curve<P::Property>,
        EasingCurve<<P as AnimatableProperty>::Property>:
            Curve<<P as AnimatableProperty>::Property>,
    {
        let mut animation = AnimationClip::default();
        let target_id = AnimationTargetId(Uuid::new_v4());

        animation.add_curve_to_target(
            target_id,
            AnimatableCurve::new(
                property,
                EasingCurve::new(start, end, ease_function)
                    .reparametrize_linear(
                        interval(0.0, time).expect("time should always be greater than 0"),
                    )
                    .expect("this curve has bounded domain, so this should never fail"),
            ),
        );

        Self {
            animation,
            target_id,
            delay: 0.0,
            init: init.into(),
        }
    }

    /// Animate [Transform::translation]
    pub fn translate(start: Vec3, end: Vec3, time: f32, ease_function: EaseFunction) -> Self {
        Self::build(
            InitialAnimateValue::Translate(start),
            animated_field!(Transform::translation),
            start,
            end,
            time,
            ease_function,
        )
    }

    /// Animate [UiTransform::translation] using [AnimatableUiTranslation] as a wrapper.
    ///
    /// See [AnimatableUiTranslation] for why this uses `Vec2` instead of `Val2`
    pub fn ui_translate(start: Vec2, end: Vec2, time: f32, ease_function: EaseFunction) -> Self {
        Self::build(
            InitialAnimateValue::UiTranslate(start),
            animated_field!(AnimatableUiTranslation::0),
            start,
            end,
            time,
            ease_function,
        )
    }

    /// Animate [Transform::rotate]
    pub fn rotate(start: Quat, end: Quat, time: f32, ease_function: EaseFunction) -> Self {
        Self::build(
            InitialAnimateValue::Rotate(start),
            animated_field!(Transform::rotation),
            start,
            end,
            time,
            ease_function,
        )
    }

    /// Animate [UiTransform::rotate]
    pub fn ui_rotate(start: Rot2, end: Rot2, time: f32, ease_function: EaseFunction) -> Self {
        Self::build(
            InitialAnimateValue::UiRotate(start),
            animated_field!(UiTransform::rotation),
            start,
            end,
            time,
            ease_function,
        )
    }

    /// Animate [Transform::scale]
    pub fn scale(start: Vec3, end: Vec3, time: f32, ease_function: EaseFunction) -> Self {
        Self::build(
            InitialAnimateValue::Scale(start),
            animated_field!(Transform::scale),
            start,
            end,
            time,
            ease_function,
        )
    }

    /// Animate [UiTransform::scale]
    pub fn ui_scale(start: Vec2, end: Vec2, time: f32, ease_function: EaseFunction) -> Self {
        Self::build(
            InitialAnimateValue::UiScale(start),
            animated_field!(UiTransform::scale),
            start,
            end,
            time,
            ease_function,
        )
    }

    /// Add delay to the animation
    pub fn with_delay(mut self, delay: f32) -> Self {
        self.delay = delay;
        self
    }
}

/// Helper component for animating ui translation, since Bevy doesn't support animating Val2
///
/// **Note**: This uses `Vec2` instead of `Val2`, so only animating in pixels is currently supported
#[derive(Clone, Component, Copy, Debug, Default, PartialEq, Reflect)]
#[reflect(Clone, Component, Debug, Default, PartialEq)]
pub struct AnimatableUiTranslation(pub Vec2);
